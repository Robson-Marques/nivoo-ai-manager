import { createHash } from 'node:crypto';

export type SkillManifestEntry={id:string;path:string;sha256:string;chars:number};
export type SkillObservation={kind:'http-page';path:string;sha256:string;start:number;end:number;total:number}|{kind:'cli-read';path:string;cli:'claude'|'gemini'};
export type SkillCoverage={id:string;sha256:string;chars:number;read:'not-observed'|'partial'|'full-local'|'cli-reported';ranges:Array<[number,number]>;cli?:'claude'|'gemini'};
export type SkillVerification={state:'not-run'|'passed'|'failed'|'interrupted';commandHash?:string;exitCode?:number|null;timedOut?:boolean};
export type SkillExecutionEvidence={version:1;provider:string;model:string|null;coverage:SkillCoverage[];verification:SkillVerification;attemptStatus:string;treeBefore:string;treeAfter:string;artifacts:string[];application:'not-independently-established'};
const sha=(v:string)=>createHash('sha256').update(v,'utf8').digest('hex');
export function manifestEntry(id:string,content:string):SkillManifestEntry{
  return {id,path:'contexto/skills-nivoo/'+id+'/SKILL.md',sha256:sha(content),chars:content.length};
}
export function verificationReceipt(command:string,exitCode:number|null,passed:boolean,interrupted:boolean,timedOut:boolean):SkillVerification{
  return {state:interrupted?'interrupted':passed?'passed':'failed',commandHash:sha(command),exitCode,timedOut};
}
function mergeRanges(ranges:Array<[number,number]>,next:[number,number]){
  const sorted=[...ranges,next].sort((a,b)=>a[0]-b[0]),out:Array<[number,number]>=[];
  for(const r of sorted){const last=out[out.length-1];if(last&&r[0]<=last[1])last[1]=Math.max(last[1],r[1]);else out.push([...r]);}
  return out;
}
/** Observations come from adapters, never parse model prose or log strings.
 * Match HTTP pages to the exact generated bytes; CLI results do not expose
 * coverage or a content hash. No inference from selected skills alone. */
export function collectSkillCoverage(manifest:readonly SkillManifestEntry[]){
  const rows=manifest.map(m=>({manifest:m,coverage:{id:m.id,sha256:m.sha256,chars:m.chars,read:'not-observed',ranges:[]} as SkillCoverage}));
  return {
    observe(event:SkillObservation){
      const row=rows.find(x=>x.manifest.path===event.path);
      if(!row)return;
      const c=row.coverage;
      if(event.kind==='cli-read'){if(c.read==='not-observed'){c.read='cli-reported';c.cli=event.cli;}return;}
      if(event.sha256!==row.manifest.sha256||event.total!==c.chars||!Number.isSafeInteger(event.start)||!Number.isSafeInteger(event.end)||event.start<0||event.end<=event.start||event.end>c.chars)return;
      const ranges=mergeRanges(c.ranges,[event.start,event.end]);
      // Bounded telemetry, not a gate. Do not invent full coverage when
      // an unusually fragmented read exceeds the retained range budget.
      if(ranges.length>256)return;
      c.ranges=ranges;
      c.read=ranges.length===1&&ranges[0][0]===0&&ranges[0][1]===c.chars?'full-local':'partial';
    },
    snapshot():SkillCoverage[]{return rows.map(x=>({...x.coverage,ranges:x.coverage.ranges.map(r=>[...r] as [number,number])}));}
  };
}
export function skillExecutionEvidence(input:Omit<SkillExecutionEvidence,'version'|'application'>):SkillExecutionEvidence{
  return {...input,version:1,application:'not-independently-established'};
}
/** Summary of co-occurrence, not causation. Only the latest successful
 * attempt of a completed step may contribute to the delivery summary. */
export function summarizeSkillEvidence(steps:readonly {id:string;status:string;attemptCount:number}[],attempts:readonly {stepId:string;number:number;status:string;contextStats:unknown}[]):string[]{
  const rows=new Map<string,{selected:number;full:number;partial:number;cli:number;passed:number}>();
  for(const step of steps){
    if(step.status!=='CONCLUIDO')continue;
    const a=attempts.find(x=>x.stepId===step.id&&x.number===step.attemptCount&&x.status==='SUCESSO');
    const e=(a?.contextStats as {skillEvidence?:SkillExecutionEvidence}|null)?.skillEvidence;
    if(e?.version!==1||e.attemptStatus!=='SUCESSO'||!Array.isArray(e.coverage))continue;
    const seen=new Set<string>();
    for(const c of e.coverage){
      if(!c||typeof c.id!=='string'||!/^[a-z0-9-]+$/.test(c.id)||seen.has(c.id))continue;
      seen.add(c.id);
      const r=rows.get(c.id)??{selected:0,full:0,partial:0,cli:0,passed:0};
      r.selected++;if(c.read==='full-local')r.full++;if(c.read==='partial')r.partial++;if(c.read==='cli-reported')r.cli++;
      if(e.verification?.state==='passed')r.passed++;
      rows.set(c.id,r);
    }
  }
  if(!rows.size)return [];
  return ['## Skills e evidências das etapas concluídas',...[...rows].sort(([a],[b])=>a.localeCompare(b)).map(([id,r])=>'- '+id+': selecionada em '+r.selected+' etapa(s); leitura local integral '+r.full+', parcial '+r.partial+', relatada pelo CLI '+r.cli+'; conferência de etapa aprovada '+r.passed+'.'),'As conferências comprovam seus próprios contratos; não demonstram causalidade nem aplicação integral de cada skill.'];
}
